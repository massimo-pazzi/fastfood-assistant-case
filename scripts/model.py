"""Данные и расчёты кейса: темы обращений, дерево сценариев, нагрузка на ассистента.

Публичных данных о причинах обращений в контакт-центр не публикует ни одна крупная сеть
быстрого питания, а заказчик статистику не предоставил. Поэтому доли тем — оценка по
открытым жалобам, отзывам и FAQ сетей быстрого питания, сделанная для предложения;
нагрузка — оценка предложения, пересчитанная из обращений в сообщения.

Результат — CSV в data/. Запуск:  python3 scripts/model.py
"""

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"

# --- Темы обращений: доля в потоке, %, (от, до) и число вариаций сценария ------------
# Вариации — подтипы обращения внутри темы, у каждой своя ветка диалога.
TOPICS = [
    ("Статус и проблемы с заказом", 30, 40, 7, "Где мой заказ, неполный заказ (возврат или довоз), не мой заказ, изменить, отменить, вернуть деньги"),
    ("Качество еды и обслуживания", 20, 25, 5, "Холодная, слишком горячая, ошибка в составе, посторонний предмет, испорченная еда"),
    ("Программа лояльности и акции", 15, 15, 5, "Баллы, активация акции, список акций, нет товара по акции, отказ в акции"),
    ("Меню и состав блюд", 10, 10, 7, "Состав, калорийность, замена и добавка ингредиентов, что есть в меню, где купить, время завтраков"),
    ("Рестораны и часы работы", 8, 8, 6, "Ближайший ресторан, часы работы, наличие позиции"),
    ("Доставка и оплата", 7, 7, 0, "Возвраты и статусы доставки покрыты сценарием заказа"),
    ("Технические проблемы с приложением", 5, 5, 6, "Не работает, регистрация, оплата в приложении"),
    ("Чистота и гигиена", 3, 3, 6, "Жалоба на ресторан — передача оператору"),
    ("Корпоративные вопросы", 2, 2, 6, "Работа в сети, корпоративные заказы"),
    ("Другое", 0, 5, 6, "Франчайзинг, спонсорство, забытые вещи"),
]

# --- Нагрузка: оценка предложения ------------------------------------------------
# Заказчик данных об активной аудитории не дал; оценка сделана по установкам приложения.
DIALOGS_PER_DAY_MAX = 750_000   # верхняя граница обращений к ассистенту в день
STEPS = (4, 6)                  # сообщений пользователя в одном обращении
ACTIVE_HOURS = 16               # часы основной нагрузки в сутки (12–16)
PEAK_DIALOGS_PER_SEC = 50       # пик новых обращений в секунду (обед, вечер, выходные)


def scenarios():
    base = len(TOPICS)
    variants = sum(t[3] for t in TOPICS)
    return base, variants, base + variants


def load():
    steps = sum(STEPS) / 2
    msgs_day = DIALOGS_PER_DAY_MAX * steps
    avg_dialogs = DIALOGS_PER_DAY_MAX / (ACTIVE_HOURS * 3600)
    peak_msgs = PEAK_DIALOGS_PER_SEC * steps
    return {"steps": steps, "msgs_day": msgs_day, "avg_dialogs_s": avg_dialogs,
            "avg_msgs_s": avg_dialogs * steps, "peak_msgs_s": peak_msgs,
            "peak_msgs_min": peak_msgs * 60}


def write(name, rows):
    DATA.mkdir(exist_ok=True)
    with open(DATA / name, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"data/{name}: {len(rows)} строк")


def main():
    write("topics.csv", [{"Тема обращения": n, "Доля в потоке от, %": lo, "Доля в потоке до, %": hi,
                          "Вариаций сценария": v, "Примеры": ex} for n, lo, hi, v, ex in TOPICS])
    L = load()
    write("load.csv", [
        {"Показатель": "Обращений в день, верхняя граница", "Значение": DIALOGS_PER_DAY_MAX},
        {"Показатель": "Сообщений пользователя в обращении", "Значение": L["steps"]},
        {"Показатель": "Сообщений в день", "Значение": round(L["msgs_day"])},
        {"Показатель": "Обращений в секунду, в среднем за 16 часов", "Значение": round(L["avg_dialogs_s"], 1)},
        {"Показатель": "Сообщений в секунду, в среднем", "Значение": round(L["avg_msgs_s"])},
        {"Показатель": "Сообщений в секунду, в пик", "Значение": round(L["peak_msgs_s"])},
        {"Показатель": "Сообщений в минуту, в пик", "Значение": round(L["peak_msgs_min"])},
    ])
    b, v, t = scenarios()
    top3 = TOPICS[:3]
    print(f"сценариев: {b} базовых + {v} вариаций = {t}")
    print(f"три главные темы: {sum(x[1] for x in top3)}–{sum(x[2] for x in top3)}% потока")
    print({k: round(x, 1) for k, x in L.items()})


if __name__ == "__main__":
    main()
